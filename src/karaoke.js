// 中文之间的空格去掉，英文单词之间保留
const kText = s => s.replace(/[()~]/g, '').replace(/(?<=[^\x00-\x7F]) +| +(?=[^\x00-\x7F])/g, '');

window.overlayHook = (c, t) => {
  for (const L of LY) if (t >= L[0] - .02 && t < L[1]) kLine(c, L, t);
};
function kLine(c, L, t) {
  const [a, b, raw, opt = {}] = L, echo = raw.startsWith('(');
  const txt = kText(raw);
  const grow = easeOut((t - a) / .18) * (1 - ease((t - (b - .14)) / .14));
  if (grow < .02) return;
  c.save();
  c.font = echo ? KFONT_E : KFONT; c.textBaseline = 'middle'; c.textAlign = 'left';
  const total = c.measureText(txt).width;
  // 主歌词居中；和声放在同一行的右侧，略微倾斜
  const cx = echo ? W / 2 + 560 : W / 2, y = KY;
  if (echo) { c.translate(cx, y); c.rotate(-.05); c.translate(-cx, -y); }
  const pad = echo ? 30 : 46, hh = echo ? 32 : 40, r = n => hash(BOILN * 13 + n) * 6 - 3;
  const w = (total + pad * 2) * (.6 + .4 * grow), x0 = cx - w / 2, y0 = y - hh;
  c.globalAlpha = (echo ? .8 : .7) * grow; c.fillStyle = echo ? '#B4462F' : PAL.ink; c.beginPath();
  c.moveTo(x0 + r(1), y0 + r(2)); c.lineTo(cx, y0 - 3 + r(3)); c.lineTo(x0 + w + r(4), y0 + r(5));
  c.lineTo(x0 + w + 12, y); c.lineTo(x0 + w + r(6), y0 + hh * 2 + r(7)); c.lineTo(cx, y0 + hh * 2 + 3 + r(8));
  c.lineTo(x0 + r(9), y0 + hh * 2 + r(10)); c.lineTo(x0 - 12, y); c.closePath(); c.fill();
  c.globalAlpha = grow;
  const n = [...txt].length, singDur = opt.sing ?? Math.min((b - a) * .85, n * .28), f = clamp((t - a) / singDur);
  const x = cx - total / 2;
  c.fillStyle = echo ? '#FFE9D6' : PAL.cream; c.fillText(txt, x, y);
  c.save(); c.beginPath(); c.rect(x - 2, y - 40, total * f + 2, 80); c.clip(); c.fillStyle = echo ? '#FFD36B' : '#8FE3C8'; c.fillText(txt, x, y); c.restore();
  c.restore();
}
